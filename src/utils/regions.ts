// 地方区分のラベル。引き（広域表示）のときに地方名を表示する。
//
// **気象庁の「地方予報区」（緊急地震速報／地方予報区・コード 99xx）に合わせてある。**
// 緊急地震速報の警報は、気象庁自身がこの単位で対象を述べる —— 警報報の見出し文が
// 「石川県で地震　北陸　甲信　東海　関東で強い揺れ」の形を採り、`Head/Headline/Information` に
// 地方予報区の一覧が入る。公式の発表や報道で耳にする地名と地図が揃っていないと、
// 聞いた地名を地図の上で探せない。
// → 利用者へ出す語を気象庁の表現と揃える方針（docs/spec/quake-spec.md §8）
//
// 従来ここに置いていた区分（北海道・東北・関東・中部・近畿・中国・四国・九州・沖縄の 9 種）
// との違いは 2 つ。
//   - **「中部」が無く、北陸・甲信・東海の 3 つに分かれる。**
//     **新潟は「北陸」に入る**（従来の区分では中部）。実電文で確認済み
//   - 島嶼が独立する（伊豆諸島・小笠原・奄美）
//
// 全 14 種。コードは 9910〜9960 に体系的に収まり、年 1 回の全国一斉訓練報
// （`Control/Status` が「訓練」の電文）が 14 種すべてを列挙する。
//
// 座標は各地方のおおよその中心。**境界データを持たないので重心ではなく手置き。**
// ラベルどうしが重なったときの逃がし方は `components/Map/LabelsGL.tsx`
// （理由と実測は docs/spec/map-rendering-spec.md §5）。
//
// 小笠原・奄美・沖縄は既定の日本全体表示（`Map/gl/bounds.ts` の `JAPAN_BOUNDS`）より南にあり、
// 引いた画（`JAPAN_WIDE_BOUNDS` へ寄せる遠地地震など）でのみ見える。伊豆諸島は枠内。
//
// **この配列を増減したら地名ラベル用グリフを焼き直すこと**（node scripts/build-glyphs.mjs）。
// build-glyphs.mjs はこのファイルを単一情報源として名前を読む。

