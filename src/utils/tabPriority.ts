/**
 * 自動タブ切替の優先度。**読み上げの優先順位（`docs/spec/audio-tts-spec.md` §6）と同じ並び**に
 * してある。声だけ優先度を持たせても画面を奪われると、EEW を読み上げている最中に別のタブが
 * 出て、肝心の予想震度・予報円が見えない。
 *
 * `manual` を EEW の続報より上、`eewUrgent` を manual より上に置いているのは既存の挙動を保つため。
 * ユーザーが自分で選んだタブを EEW の続報に奪わせないが、**新規発報・レベルアップ・誤報取消は
 * 手動選択より強い**（危険の通知は見せる側が優先する）。
 */
export const TAB_PRIORITY = {
  /**
   * 地震情報と長周期地震動情報。すでに起きた地震の事後情報。
   *
   * **長周期を地震情報と同格にしている**のは読み上げ側と揃えるため（`SPEECH_PRIORITY.normal`）。
   * 長周期は地震情報より新しい情報なので、待たせるのではなく割り込ませる。どちらも移動先は
   * 地震情報タブなので、同格にしてもタブの奪い合いは起きない。
   */
  quake: 1,
  /** 強震モニタの揺れ検知。「いま揺れている」を示すので地震情報より重い */
  kyoshin: 2,
  /** 津波。避難行動を促すため揺れ検知より重い */
  tsunami: 3,
  /** EEW の続報 */
  eewUpdate: 4,
  /** ユーザーの手動選択 */
  manual: 5,
  /** EEW の新規発報・レベルアップ・誤報取消 */
  eewUrgent: 6,
} as const

export type TabPriority = typeof TAB_PRIORITY[keyof typeof TAB_PRIORITY]

/**
 * 自動タブ切替の保持時間。この間、これより低い優先度の自動切替を拒否する。
 * EEW は続報のたびに張り直されるため、系列が続いている間は自然に守られる。
 */
export const TAB_HOLD_MS = 15000

/**
 * 自動タブ切替の駆動源。
 *
 * - `speech`: 読み上げの発話に同調した追従。順序は読み上げ側（`waitForSpeechSlot` /
 *   `chainEEWSpeech`）が既に決めているため、タブ側で重ねて順序を守る必要がない
 * - `idleRevert`: 既定の状態へ戻す操作。**読み上げ追従には譲る**（理由は `shouldAcceptAutoTab`）。
 *   該当するのは、アイドル復帰が realtime に留まる経路と、`revertToDefaultTab` を通る復帰すべて
 *   （アイドル復帰・EEW 全解除・揺れ検知終了・揺れの可能性の失効）
 * - `receipt`: **読み上げが無効な端末**での電文の受信。その電文は声にならないため、画面が唯一の
 *   伝え手になる。**EEW の続報が確保した画面を越える**（理由は `shouldAcceptAutoTab`）
 * - `hold`: ユーザー操作・揺れ検知、および**読み上げが有効な端末で読み上げ文が空になった電文**。
 *   最後のものを `receipt` に含めない理由——本来は追従で動く電文なので、越えさせると EEW を
 *   実際に読み上げている最中に画面を奪う（振り分けは `setActiveTabNonRealtime`）
 */
export type TabHoldSource = 'speech' | 'idleRevert' | 'receipt' | 'hold'

/**
 * 電文の受信でタブを要求するときの駆動源を決める（呼び出し元は `setActiveTabNonRealtime`）。
 *
 * - 読み上げが**無効**なら `receipt`。その電文はそもそも声にならないので画面が唯一の伝え手になる
 * - 読み上げが**有効**なら `hold`。この経路に来るのは「読み上げ文が空になった」ときだけで、本来は
 *   追従で動く電文。越えさせると EEW を実際に読み上げている最中に画面を奪う
 *
 * **三項演算子 1 行を関数にしてあるのはテストで固定するため。** どちらの値も `TabHoldSource` として
 * 妥当なので、取り違えても型チェックは通る。取り違えたときに出る症状は「EEW 発表中に画面が動かない」
 * か「読み上げ中の EEW から画面を奪う」のいずれかで、**どちらも一度直した症状**。
 */
export function resolveNonRealtimeTabSource(voicevoxEnabled: boolean): TabHoldSource {
  return voicevoxEnabled ? 'hold' : 'receipt'
}

/** 自動タブ切替の保持状態。「いつまで」「どの優先度で」「どちらの駆動で」確保しているか。 */
export interface TabHold {
  until: number
  priority: TabPriority
  source: TabHoldSource
}

/**
 * 自動タブ切替を受け付けてよいかを判定する。
 *
 * 保持が切れていれば通す。保持中でも**同格以上なら通す**（新しい情報が勝つ。読み上げと同じ規則で、
 * 震度速報の更新が古い震度速報を置き換えるのと同じ考え方）。低い優先度だけを拒否する。
 *
 * ただし**読み上げ追従どうしは保持を見ない**。順序は読み上げ側が既に決めているため、ここで
 * 二重に守ると「読み終わった電文の保持の残り」が次に読む電文を弾く。実測では、読み終えた EEW の
 * 保持（優先度 6・残り 12.8 秒）に大津波警報（3）と震度速報（1）が弾かれ、声だけが喋って
 * 画面が動かない状態になっていた（2026-08-20）。
 *
 * 逆に、読み上げを持たない経路（手動選択・読み上げ無効時の受信）が絡む組み合わせでは
 * 従来の優先度比較を残す。これらは順序を決める仕組みを他に持たないため。
 * 例外が 3 つあり、いずれも保持の側が譲る（下記）——揺れ検知の保持は読み上げの有無に関わらず
 * 他の移動を妨げず、アイドル復帰の保持は読み上げ追従を妨げず、**EEW 続報の保持は電文の受信
 * （`receipt`）を妨げない**。
 *
 * @param source 要求の駆動源。**既定値を残しているのはテストを読みやすくするため。** 本番の
 *   呼び出しは `requestAutoTab` の 1 箇所だけで、そこは常に明示している。保持を張る側
 *   （`forceTab`）は逆に既定値を撤廃してある——あちらは復帰経路を足すときに渡し忘れが起きうる。
 */
export function shouldAcceptAutoTab(
  hold: TabHold,
  priority: TabPriority,
  now: number,
  source: TabHoldSource = 'hold',
): boolean {
  if (hold.until - now <= 0) return true
  // **揺れ検知の保持は、他の情報の移動を妨げない。** 揺れ検知は「いま揺れている」を realtime で
  // 見せるための移動だが、そこに地震情報が届いたなら地震情報を見せてよい（実際に起きた順序どおり
  // なので、画面が留まる方が不自然）。読み上げの有無に関わらず同じ扱いにする。
  // 揺れ検知の続き（レベルアップ・別地点）は自分で要求を出し直すため、必要なら realtime へ戻る。
  if (hold.priority === TAB_PRIORITY.kyoshin) return true
  // **EEW の続報は、他の情報が確保している画面を奪わない。** 従来からある片方向の抑制で、
  // 「非 realtime タブへ移ったあとは EEW の続報で realtime へ引き戻さない」もの。
  // 抑制が無いと、津波や地震情報を読み上げて画面を移した直後に続報が来て realtime に戻り、
  // 数秒ごとに画面が往復する（読み上げは続いているのに画面だけが行き来する）。
  // 同じ系列で realtime を確保している間（保持が EEW 由来）は素通りさせる。
  // 新規発報・レベルアップ・誤報取消は `eewUrgent` で要求されるため、この抑制に掛からない。
  if (priority === TAB_PRIORITY.eewUpdate
    && hold.priority !== TAB_PRIORITY.eewUpdate
    && hold.priority !== TAB_PRIORITY.eewUrgent) {
    return false
  }
  // **読み上げを持たない電文の受信は、EEW の続報が確保した画面を越える。** 直上の片方向抑制と
  // 対になる規則。旧実装（優先度の仕組みを入れる前の `realtimeTabSuppressedUntilRef`）は
  // 「realtime 以外へ移った瞬間に 15 秒の抑制を張る」形で、移動そのものは無条件だった。
  // 優先度で裁くようにした際にこちら側が落ち、**読み上げが無効な端末では EEW 発表中に震度速報も
  // 津波警報も画面へ出せなくなっていた**（優先度 1・3 が続報の 4 に弾かれる。続報は数秒おきに
  // 保持を張り直すため保持が切れず、津波の続報は数分間隔なので待っても順番が来ない）。
  // **この駆動源で出るのは読み上げが無効な端末だけ**（振り分けは `setActiveTabNonRealtime`）。
  // 読み上げが有効な端末は下の追従の判定で通り、読み上げ文が空になった電文は `hold` で出る
  // ——そちらを越えさせると、EEW を実際に読み上げている最中に画面を奪ってしまう。
  //
  // **越える相手を `eewUpdate` に限ること。** `eewUrgent`（新規発報・レベルアップ・誤報取消）
  // まで広げると、誤報取消のオーバーレイ表示中に無関係な地震情報でタブが消える（優先度の
  // 仕組みを入れたときに直した症状）。保持は「最後に動いた理由」で上書きするため、続報が
  // 1 本届けば 4 に落ちて越えられるようになる——EEW は続報が数秒おきに来るので、6 の保持が
  // 15 秒残り切る場面はほとんど無い。
  //
  // アイドル復帰が EEW 発表中に張る保持（`eewUpdate` / `idleRevert`）もこの判定で越える。
  // 復帰の駆動源を見る必要はない——揺れ検知中の復帰は 2 で張るので上の判定が通し、既定タブへの
  // 復帰は 1 なので末尾の優先度比較が通す。
  //
  // **画面を取ったあとは直上の片方向抑制が 15 秒守る。** 抑制は元から在ったが、前段のここが
  // 塞がっていたため一度も発火していなかった。
  if (source === 'receipt' && hold.priority === TAB_PRIORITY.eewUpdate) return true
  // **アイドル復帰の保持は、読み上げ追従を妨げない。** アイドル復帰は新しい情報ではなく
  // 「既定の状態へ戻す」操作なので、そこへ読み上げの始まる電文が届いたなら画面を合わせる方が筋。
  // 妨げていた実害: EEW 発表中の復帰は `eewUpdate`（4）で張るため、電文が 30 秒途切れるたびに
  // 15 秒のブロック窓が開き、そこへ落ちた地震情報（1）・津波（3）が声だけ喋って画面が動かない
  // （2024/8/8 日向灘 M7.1 のリプレイで実測。16:46:22 の復帰が 16:46:26 の震源・震度情報を弾き、
  // 22 秒後の震度速報は保持が切れていたため移動していた）。
  // **譲った結果、EEW の表示（realtime）へはしばらく戻らない。** 追従が画面を取ると保持の重みは
  // その電文のもの（地震情報なら 1）に下がり、以後の EEW 続報は上の片方向抑制で弾かれる。
  // 戻る契機は 2 つだけ——電文が `idleRevertSec` のあいだ途切れて次の復帰が発火するか、
  // 新規発報・レベルアップ・誤報取消（`eewUrgent`）が届くか。**続報が続いている EEW ほど前者は
  // 起きにくい**（受信のたびに復帰タイマーが延びる）。
  // それでも譲る方を採るのは、声と画面が食い違う実害の方が大きいため。EEW は通知音・タイトル・
  // ブラウザ通知でも伝わるが、いま読み上げている電文の中身はその画面にしか出ない。
  //
  // 読み上げを持たない経路（受信時要求・手動選択・揺れ検知）に対しては従来どおり優先度で判定する。
  // ここを駆動源で判定しているのは、優先度を下げる（4→2）だけでは地震情報（1）が依然弾かれるため。
  if (hold.source === 'idleRevert' && source === 'speech') return true
  // 追従どうしは順序が保証されているので保持を見ない。
  //
  // **ここを「手動選択以外は全部突破する」まで広げてはいけない。** 広げると、区域を持たない
  // 津波電文で受信時要求に落としたフォールバック（`tsunami`）を地震情報・長周期（`quake`）が
  // 即座に奪う。譲らせる相手は駆動源で名指しすること（上の揺れ検知・アイドル復帰がその形）。
  if (source === 'speech' && hold.source === 'speech') return true
  return priority >= hold.priority
}

/**
 * 先出しで既に画面を取れていた電文が、発話の瞬間に**取り返しに行くべきか**。
 *
 * 通常の読み上げは 1 つの電文につき 2 回タブを要求する（受信時の先出しと、発話の瞬間の追従）。
 * 2 回目は「先出しのあと別の情報に画面を奪われていたら取り戻す」ためにある。
 *
 * **ただし揺れ検知に奪われた場合は取り返さない。** 取り返すと次の並びで画面が往復する:
 * 先出しで earthquake → 揺れ検知のレベルアップで realtime → 発話の瞬間に earthquake →
 * 次のレベルアップでまた realtime。強震モニタは 1 秒ごとにフレームが来るので、通知音との間
 * （地震情報系は 0.5〜1.7 秒）にレベルアップ判定が 1〜2 回入る。EEW の続報に片方向抑制を
 * 入れているのと同じ理由で、**往復の方が食い違いより悪い**。
 *
 * **読み上げを持つ相手に奪われた場合は取り返す。** 読み上げは待ち行列で順番が直列に保証されて
 * いるため、取り返しても往復にならない（相手は自分の番を終えている）。ここを一律に止めると、
 * 近接して届いた 2 つの電文が互いの先出しを上書きし合ったとき、**後で声に出る側の画面が
 * 二度と戻らない** —— この仕組みが解消したかった「声と画面の食い違い」そのものが別の形で出る。
 *
 * **見送るのは揺れ検知そのものが張った保持だけ**（`requestTabForKyoshin` ＝ `hold` 駆動）。
 * 揺れ検知中のアイドル復帰も同じ優先度で張るが（`idleRevertPriority`）、そちらは
 * `idleRevertSec`（既定 30 秒・選べる最短で 15 秒）に 1 回しか発火しないので往復の原因に
 * ならない。駆動源を見ずに
 * 優先度だけで弾くと、**キュー待ちで長く待たされた読み上げが、直前のアイドル復帰に阻まれて
 * 声だけ出て画面が動かない** —— 「アイドル復帰の保持は読み上げ追従を妨げない」という
 * `shouldAcceptAutoTab` 側の規則（判定の 5）を、こちらが静かに破ることになる。
 *
 * 保持が切れていれば誰も守っていないので取り返す。
 */
export function shouldRetakeAfterPreSpeech(hold: TabHold, now: number): boolean {
  if (hold.until - now <= 0) return true
  return !(hold.priority === TAB_PRIORITY.kyoshin && hold.source === 'hold')
}

/**
 * 読み上げ追従が続けて発火するときの最小滞留時間。
 *
 * VOICEVOX が起動していない端末では、合成が 1 チャンクも通らないまま発話がほぼ即座に終わる。
 * すると読み上げの行列が一瞬で捌け、**声は一切出ないのにタブだけが激しく入れ替わる**。
 * 床を置いて間引く。
 */
export const TAB_FOLLOW_MIN_DWELL_MS = 1500

/** 直前の読み上げ追従の記録（いつ・どの優先度で動いたか）。 */
export interface TabFollowMark {
  at: number
  priority: TabPriority
}

/**
 * 読み上げ追従を今すぐ発火してよいかを判定する。
 *
 * 直前の追従より**重い情報は待たせない**（EEW が津波の読み上げに割り込んだ場合など、
 * 声が切り替わっているのに画面が遅れるのを防ぐ）。同格以下の連続だけを床で間引く。
 *
 * **床を読む要求と、床（`TabFollowMark`）を進める要求は同じ集合に保つこと。** 進める側だけを
 * 広く取ると、床を読まない要求（通知音と同時の先出し・EEW の受信時要求）が床を押し上げ、
 * 後から実際に声が出る側の追従を弾く。呼び出し側の条件は `App.tsx` の `requestAutoTab` にある。
 */
export function shouldFollowNow(
  last: TabFollowMark | null,
  priority: TabPriority,
  now: number,
): boolean {
  if (last === null) return true
  if (priority > last.priority) return true
  return now - last.at >= TAB_FOLLOW_MIN_DWELL_MS
}

/**
 * アイドル復帰で realtime に留めるときの優先度を決める。
 *
 * EEW 発報中は続報が続く系列の途中なので `eewUpdate` で確保してよいが、**揺れ検知だけのときに
 * 同じ重みを使ってはいけない**。優先度表（揺れ検知 2 ＜ 津波 3）が逆転し、津波警報や
 * 「別地点で揺れ検知」が画面を取れなくなる。実測では揺れ検知が続く間、30 秒周期で 15 秒の
 * ブロック窓が開き続けていた（2026-08-20・2024/1/1 能登前震のリプレイで確認）。
 *
 * ここで決まる重みが効くのは、読み上げを持たない要求（受信時要求・手動選択）に対してだけ。
 * 読み上げ追従は駆動源で通す（`shouldAcceptAutoTab`）。
 */
export function idleRevertPriority(hasActiveEew: boolean): TabPriority {
  return hasActiveEew ? TAB_PRIORITY.eewUpdate : TAB_PRIORITY.kyoshin
}
