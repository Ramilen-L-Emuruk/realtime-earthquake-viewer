// 計算した震度の値を、気象庁が公表する形（小数 1 桁）へ直す。
//
// 気象庁の「計測震度の算出方法」は最後に「計算された I の小数第３位を四捨五入し、
// 小数第２位を切り捨てたものを計測震度とする」と定め、**階級はその値で引く**。
// 2.46 は 2.4（四捨五入の 2.5 ではない）、2.4951 は 2.50 を経て 2.5 で震度3。
//
// **数字も階級もここを通す。** 数字だけを別の丸め方で出すと、2.495〜2.5 未満のような
// 細い帯で「2.5・震度2」が出る（数字から読める階級と、添えた階級が食い違う）。
// 使う側は地図の左上の帯・地震カード・波形の詳細（PWA）と、ホストの管理コンソール。
//
// **何も読み込まない。** 管理コンソールも読むので、ここが画面側のロガーなどを
// 引き込むと、あちらの束にまで入る。

/**
 * 気象庁の手順で直した計測震度を、**十分の一単位の整数**で返す（2.46 → 24）。
 *
 * **整数で返すのは浮動小数の罠を避けるため。** `Math.floor(2.3 * 10)` は
 * `22.999…` を切って 22 になる。百分の一の整数へ丸めてから 10 で割って切り捨てれば、
 * 途中に誤差の入る掛け算が無い。
 *
 * **負の値は 0 へ向けて切り捨てる**（`-0.04` は 0、`-0.15` は -1）。気象庁の階級表は
 * 0.5 未満をすべて震度0 とするので、どちらへ切っても階級は変わらない。静穏時によく出る
 * `-0.04` を「0.0」のまま見せられる向きを採った。
 *
 * 非有限の値は渡さないこと（`NaN` を返す）。弾くのは呼び出し側の仕事。
 */
export function jmaMeasuredTenths(value: number): number {
  const hundredths = Math.round(value * 100)
  const tenths = Math.trunc(hundredths / 10)
  // `Math.trunc(-0.4)` は `-0`。比べる分には 0 と同じだが、文字にすると符号が出うるので潰す。
  // **`|| 0` で潰さない** —— `NaN` まで 0 に化け、壊れた値が「0.0」として出る。
  return tenths === 0 ? 0 : tenths
}

/**
 * 計測震度を小数 1 桁の文字列にする（気象庁の手順。**マイナスゼロを出さない**）。
 *
 * 静穏時のホストは `-0.04` のようなわずかな負の値をよく返す。`"-0.0"` は表示が
 * 壊れたようにしか見えない —— 地図の左上の帯は「地震計が生きている」ことを示すのが
 * 主な役目なので、いちばん起こしたくない誤解になる。
 */
export function formatMeasured(value: number): string {
  return (jmaMeasuredTenths(value) / 10).toFixed(1)
}
