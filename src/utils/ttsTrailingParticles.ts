// 辞書キーの直後に続く助詞の列挙と切り出し。
//
// **辞書の読み込み（`ttsPhraseBreakDict.ts`）から分けてあるのは、外部依存を持たせないため。**
// あちらは生成データの取得を抱えており、読み込むだけで `import.meta.env`（Vite が注入する値）を
// 評価する。Node から import すると **そこで落ちる**ので、検証スクリプト
// （`scripts/verify-particle-phrases.ts`）が列挙を実装から取れない。字面を正規表現で抜く形に
// 逃げると、**助詞を足したときに検証だけが古い集合で通り続ける**。
//
// **ここには import を足さないこと。** 足した時点で上の理由が崩れ、検証が実装から離れる。

/**
 * 辞書キーの直後に続く付属語（助詞）と、その読み。**長い順に並べること**（{@link leadingParticle}
 * が先頭から順に当てるので、`で` が先にあると `では` を取りこぼす）。
 *
 * **これは「辞書の読みへ足し戻す」ための表。** 辞書の値は名前だけの読みだが、生成側は
 * 読み上げ文が実際に作る形（`〇〇、` と `〇〇では、`）で誤読を判定し、そこから助詞ぶんの読みを
 * 差し引いて収録している（`scripts/build-station-readings.ts` の `STATION_SPEECH_CONTEXTS`）。
 * ここで足し戻すと、判定したときと同じモーラ列が再現される。
 *
 * **表記をカタカナにするだけでは作れない読みがある。** 係助詞の「は」は `ワ`・目的格の「を」は `オ`・
 * 方向の「へ」は `エ`。
 *
 * **`へ` は津波の観測情報が更新の着点を受ける助詞**（「〇〇で16時32分の押し波へ更新されました。」）。
 * 押し引きの語（`押し波` / `引き波`）は手書きの句区切り辞書の `_terms` にあるので、**辞書キーの直後に
 * `へ` が来る形が実在する**。着点を「に」で受けていた頃は `に` が取り込んでいた。
 *
 * **ここに無い助詞は取り込まず、従来どおり辞書キーの直後で句を切る**（{@link leadingParticle}
 * が null を返す）。取りこぼしても挙動は変わらない。
 *
 * **入れてよいのは `ttsText.ts` の文型に実在するものだけ。実データでの出現件数は基準にしない。**
 * 主格の `が` は津波の等級が動く報に実在する（「〇〇の大津波警報が津波注意報に切り替えられました。」
 * 「大津波警報が発表されました。」）—— **文型を洗い出すときは、辞書キーが `_terms` の側にある形も
 * 数えること。** 地名の後ろだけを見ると、津波区分の語（`大津波警報` ほか）に続く助詞を取りこぼす。
 * 読み上げ文へ出た名前が辞書キーに当たるかは電文次第なので、文型が実在しても実データでは 0 件に
 * なりうる（`にも` は津波の「〇〇にも津波警報が発表されています。」の文型にあるが、実測 12,688
 * 箇所では 0 件だった）。**逆に、文型に無いものは入れない** —— 判定は字面だけなので、助詞に
 * 見えて語の一部である並びを切りうる（`も` を入れると気象庁が書いた文の「もしくは」を
 * `モ` ＋「しくは」に割る）。 **`でも` は列挙にあるが `も` は無い**のはこのため —— 前者は
 * 緊急地震速報の警報対象地方（「新たに、〇〇でも強い揺れに警戒してください。」）の文型に実在し、
 * 2 文字あるので語の一部を切る余地が小さい。**`でも` を落とすと最長一致で `で` だけが取り込まれ、
 * 残った `も` が 1 モーラの独立したアクセント句として浮く**（実測）。文型の洗い出し方と実測の数え方は
 * `docs/spec/audio-tts-spec.md` §3「助詞は辞書の読みへ取り込む」にある。
 *
 * **列挙を export しているのは検証スクリプトのため。** `npm run verify-particle-phrases` が
 * これと実データの辞書を突き合わせ、読みへ連結してもアクセント句の数が変わらないことを確かめる。
 */
export const TRAILING_PARTICLES: readonly (readonly [surface: string, kana: string])[] = [
  ['では', 'デワ'],
  ['でも', 'デモ'],
  ['にも', 'ニモ'],
  ['が', 'ガ'],
  ['で', 'デ'],
  ['は', 'ワ'],
  ['を', 'オ'],
  ['の', 'ノ'],
  ['に', 'ニ'],
  ['へ', 'エ'],
]

/**
 * `key` が {@link TRAILING_PARTICLES} の助詞で終わるか。**辞書キーを渡すこと。**
 *
 * 見分けたいのは**助詞まで鍵に含めた形**（`最大震度4を`・`グアテマラを`）。記法では核の位置を
 * 辞書の値の中にしか書けないので、核を助詞へ置きたいときは鍵の側へ含めるしかない
 * （→ `docs/spec/audio-tts-spec.md` §3「鍵に助詞まで含める場合」）。
 *
 * **その鍵の直後は名前の切れ目ではなく文の途中**なので、間を挟まない（挟むと
 * 「〇〇を［間］震源とする」と述語から切り離れて聞こえる）。判定は字面だけなので、
 * 助詞に見えて語の一部である並び（ひらがなで終わる地名）も真を返しうるが、**外れても
 * 間が入らなくなるだけ**で読みは変わらない。
 */
export function endsWithParticle(key: string): boolean {
  return TRAILING_PARTICLES.some(([surface]) => key.endsWith(surface))
}

/**
 * `text` の先頭にある付属語を返す（無ければ null）。辞書キーの直後の断片を渡すこと。
 *
 * **これを取り込む目的は、助詞が独立したアクセント句になるのを防ぐこと。** 辞書キーだけを
 * `is_kana=true` で合成すると、後続の助詞は別の断片の先頭になり、1 モーラで自らアクセント核を
 * 持つ句として鳴る（実測: 話者 6 で「宮古で〜」の `デ` が `accent=1` の単独句）。日本語に
 * 附属語だけのアクセント句という形は無いため、そこが繋ぎ目の違和感になる。
 * 読みを辞書の値へ足して同じ句に入れると、核の後ろで下降する形になり、通しで合成したときと
 * ほぼ同じ構造になる（→ `docs/spec/audio-tts-spec.md` §3「助詞は辞書の読みへ取り込む」）。
 *
 * **判定は字面だけ。** 助詞に見えて語の一部である並びは区別できないので、切る余地は
 * {@link TRAILING_PARTICLES} の列挙で狭めている（何を入れてよいかの基準はそちらに書いてある）。
 */
export function leadingParticle(text: string): { surface: string; kana: string } | null {
  for (const [surface, kana] of TRAILING_PARTICLES) {
    if (text.startsWith(surface)) return { surface, kana }
  }
  return null
}
