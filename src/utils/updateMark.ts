/**
 * カードに「この報で何が動いたか」を示す印の、共通の語彙。
 *
 * 津波・地震・長周期・緊急地震速報のどのカードでも**同じ色を同じ意味で使う**。
 * 別々に持つと、読み手がカードごとに色の意味を覚え直すことになる。
 *
 * **2 段構え。** 行の左端の縦線が「この行で何かあった」、項目ごとの印が「この項目よ」。
 * 片方だけでは足りない —— 縦線だけでは項目の多い行でどこを見ればよいか分からず、
 * 項目の印だけでは畳んだ行に何かあることが伝わらない。
 *
 * **項目の印の出し方はカードで違う。色の語彙だけを共有する。**
 *
 * - 地震カードの欄 … **値の肩に置く点**（→ `components/UpdateDot.tsx`）。欄は 6 つが横に並び、
 *   そのうち津波区分は文字そのものが区分の色なので、文字色では揃えられない
 * - 津波カードの観測点の行 … **文字色**。1 行に時刻・波高が並ぶだけなので、動いた項目を
 *   直接塗るほうが指しやすい（波高の既定を白にして、等級の色との衝突を外した）
 */

/**
 * 印の意味。
 *
 * **値に大小があるものは向きまで示す。** 「動いた」だけでは、規模が 6.5 から 6.8 へ上がったのか
 * 7.1 から 6.8 へ下がったのかが色から読めない。緊急地震速報は続報で規模が 45.0% の確率で動く
 * （控え 8 日・続報 1,184 通の実測）ので、向きが分かるかどうかで読み取れる量が変わる。
 *
 * - `new` … 初めて値が付いた／行が現れた
 * - `raised` … 値が上がった（より深刻に）
 * - `lowered` … 値が下がった（より軽く）
 * - `changed` … 動いたが大小が無い（震央地名・座標・時刻など）
 */
export type UpdateStatus = 'new' | 'raised' | 'lowered' | 'changed'

/**
 * 持続する印の色（津波・地震・長周期のカード）。**緑＝初めて現れた・黄＝動いた。**
 *
 * **向きでは分けない。** これらのカードは報の間隔が分の単位で、値そのものが画面に出たまま
 * 残る。印の仕事は「どこを見ればよいか」を指すことで、上がったか下がったかは**値を見れば
 * 分かる**。色を増やすと、読み手が覚える語彙だけが増える。
 *
 * **向きで分けるのは緊急地震速報だけ**（→ {@link EEW_FLASH_COLOR}）。あちらは値が秒ごとに
 * 書き換わって追えないので、色が向きを持つ意味がある。
 *
 * **区別そのものは `UpdateStatus` が保っている**ので、色を分け直すことはいつでもできる。
 * 欄に添える言葉（{@link UPDATE_MARK_TITLE}）は向きまで言う。
 */
export const UPDATE_MARK_COLOR: Record<UpdateStatus, string> = {
  new: '#4ade80',
  raised: '#fbbf24',
  lowered: '#fbbf24',
  changed: '#fbbf24',
}

/**
 * 緊急地震速報の減衰の色。**赤＝上がった・緑＝下がった・白＝大小が無い。**
 *
 * **ここだけ向きで分ける。** 続報が秒の単位で届いて値を追えないので、「どちらへ動いたか」を
 * 色が持つ意味がある（実測で規模は 45.0% の続報で動く）。危険が増した方を暖色に置くのは
 * 地図の震度色と同じ向きで、説明されなくても読める。
 *
 * **`new` は使わない。** 初めて現れた値は「動いた」ではないので、減衰そのものが起きない。
 */
export const EEW_FLASH_COLOR: Record<UpdateStatus, string> = {
  new: '#ffffff',
  raised: '#f87171',
  lowered: '#4ade80',
  changed: '#ffffff',
}

/**
 * 緊急地震速報で、元から白い文字に `changed`（白）を出すための背景。
 *
 * 文字色を白にしても何も変わらないので、背後をうっすら光らせる。**色相を足さない**という
 * `changed` の考え方は保ったまま、白い文字でも変化が見えるようにする。
 */
export const UPDATE_MARK_WASH = 'rgba(255, 255, 255, 0.22)'

/**
 * 写し取った 1 つの値。
 *
 * - `key` … 同じ値かどうかを見るための文字列。**表示に使う値をすべて畳み込む**
 *   （階級だけでなく未入電かどうか、規模なら数値と説明、など）
 * - `rank` … 大小を比べられるなら、その順序。**比べられない値には付けない**
 *   —— 付けないことが「この欄の変化に向きは無い」という意味になる
 */
export interface SnapshotValue {
  key: string
  rank?: number
}

/**
 * 前の値と今の値から印を決める。**同じなら `undefined`。**
 *
 * 大小を比べられる（両方に `rank` がある）ときだけ向きを出す。片方でも比べられなければ
 * 「動いた」までしか言えないので `changed`。
 *
 * **初出（`new`）はここでは決めない。** 「値が無かった」と「値はあったが比べられない」は
 * 呼び出し側の事情で表し方が違う（欄は番兵、行は鍵の不在）ため。
 */
export function statusOf(before: SnapshotValue, after: SnapshotValue): UpdateStatus | undefined {
  if (before.key === after.key) return undefined
  if (before.rank !== undefined && after.rank !== undefined && before.rank !== after.rank) {
    return after.rank > before.rank ? 'raised' : 'lowered'
  }
  return 'changed'
}

/**
 * 印の中身。`fields` はその行の中で動いた項目の集合で、項目の名前はカードごとに違う。
 *
 * **`fields` が空の印もありうる**（行そのものが初出で、中の項目の差分は問わない場合）。
 * 空を「印が無い」と取り違えないこと —— 縦線は `status` だけで決まる。
 */
export type UpdateMark<F extends string> = {
  status: UpdateStatus
  fields: ReadonlySet<F>
}

/**
 * 印の意味を言葉で言う（欄に添えるツールチップ）。
 *
 * **色だけを手掛かりにしない。** 色の違いを読み取れない利用者には、印は何も伝えない。
 * ただし**印は情報そのものではない** —— 値・行はどれも印なしで読める形で出ているので、
 * ここで補うのは「この報で動いた」という案内だけ。
 */
export const UPDATE_MARK_TITLE: Record<UpdateStatus, string> = {
  new: '最新の情報で初めて出た値です',
  raised: '最新の情報で上がりました',
  lowered: '最新の情報で下がりました',
  changed: '最新の情報で変わりました',
}

/**
 * 印が消えるまでの時間。**次の報が来ればそちらで置き換わる**ので、これは
 * 「次が来ないまま放置されたとき」の上限。
 *
 * **報の間隔に合わせてある。** 津波の観測情報と地震情報は分の単位で届くので、
 * 1 分残しても次の報と重ならない。緊急地震速報だけは秒の単位で届くため、
 * 同じ長さにすると印が消える前に次が来て**常時点灯**になる（実測: 控え 8 日・
 * 続報 1,184 通で、規模が 45.0%・座標が 35.9% の続報で動いていた）。あちらは
 * {@link EEW_HIGHLIGHT_FADE_MS} をかけて元の色へ戻す。
 */
export const UPDATE_MARK_TTL_MS = 60000

/**
 * 緊急地震速報で、動いた欄の色が元へ戻りきるまでの時間。
 *
 * **持続させないのは、報の間隔が短いから。** 印を残す作りにすると次の報が来る前に
 * 消えず、カードが光りっぱなしになって「今この欄が動いた」を指せなくなる。
 *
 * **点けたり消したりはしない。** 値が動いた瞬間に印の色へ切り替え、そこから
 * なめらかに元の色へ戻す（CSS のトランジション）。点滅は秒単位で届く続報のたびに
 * 起きると目が休まらず、画面を見続ける使い方に向かない。
 *
 * **はじめの {@link EEW_HIGHLIGHT_HOLD_RATIO} のあいだは色を保つ。** 保たずに落とすと、
 * 減衰が速すぎて何色だったのか読めないまま終わる（実機で「違いが分かりにくい」と分かった）。
 */
export const EEW_HIGHLIGHT_FADE_MS = 1000

/**
 * 減衰の前に色を保つ割合（`update-fade-text` の keyframes と揃える）。
 *
 * **ここを変えたら `src/index.css` の `@keyframes update-fade-text` も直すこと。**
 * CSS 側は割合で書くため、この定数から自動では決まらない。
 */
export const EEW_HIGHLIGHT_HOLD_RATIO = 0.35
